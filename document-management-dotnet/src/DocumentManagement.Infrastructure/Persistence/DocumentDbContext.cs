using DocumentManagement.Application.Abstractions;
using DocumentManagement.Domain.Common;
using DocumentManagement.Domain.Entities;
using Microsoft.EntityFrameworkCore;
using Microsoft.EntityFrameworkCore.Metadata.Builders;

namespace DocumentManagement.Infrastructure.Persistence;

/// <summary>
/// EF Core context with row-level multi-tenancy: every query on tenant-owned aggregates is filtered by the
/// caller's tenant and excludes soft-deleted rows. The filter reads <see cref="CurrentTenantId"/> per context
/// instance, so it is evaluated per request rather than baked into the cached model.
/// </summary>
public sealed class DocumentDbContext(DbContextOptions<DocumentDbContext> options, ICurrentUser currentUser) : DbContext(options)
{
    public Guid CurrentTenantId => currentUser.TenantId;

    public DbSet<Document> Documents => Set<Document>();

    public DbSet<Folder> Folders => Set<Folder>();

    protected override void OnModelCreating(ModelBuilder modelBuilder)
    {
        modelBuilder.Entity<Document>(ConfigureDocument);
        modelBuilder.Entity<Folder>(ConfigureFolder);

        modelBuilder.Entity<DocumentVersion>(version =>
        {
            version.ToTable("document_versions");
            version.Property(v => v.Notes).HasMaxLength(1000);
            version.Property(v => v.StoragePath).HasMaxLength(1000);
            version.Property(v => v.FileHash).HasMaxLength(128);
            version.Ignore(v => v.VersionNumber);
            version.HasIndex(v => new { v.DocumentId, v.MajorVersion, v.MinorVersion }).IsUnique();
        });

        modelBuilder.Entity<DocumentTag>(tag =>
        {
            tag.ToTable("document_tags");
            tag.Property(t => t.Name).HasMaxLength(100);
            tag.Property(t => t.Value).HasMaxLength(500);
            tag.Property(t => t.TagType).HasMaxLength(50);
            tag.HasIndex(t => new { t.DocumentId, t.Name }).IsUnique();
            tag.HasIndex(t => t.Name);
        });

        modelBuilder.Entity<DocumentPermission>(permission =>
        {
            permission.ToTable("document_permissions");
            permission.Property(p => p.PrincipalId).HasMaxLength(450);
            permission.Property(p => p.PrincipalType).HasMaxLength(20);
            permission.Property(p => p.GrantedBy).HasMaxLength(450);
            permission.HasIndex(p => new { p.DocumentId, p.PrincipalType, p.PrincipalId }).IsUnique();
        });

        modelBuilder.Entity<DocumentComment>(comment =>
        {
            comment.ToTable("document_comments");
            comment.Property(c => c.Content).HasMaxLength(2000);
            comment.Property(c => c.AuthorId).HasMaxLength(450);
            comment.Property(c => c.AuthorName).HasMaxLength(200);
            comment.Property(c => c.ResolvedBy).HasMaxLength(450);
        });

        foreach (var entityType in modelBuilder.Model.GetEntityTypes().Where(t => typeof(BaseEntity).IsAssignableFrom(t.ClrType)))
        {
            var entity = modelBuilder.Entity(entityType.ClrType);
            entity.Ignore(nameof(BaseEntity.DomainEvents));
            // Keys are generated by the domain (UUIDv7), so new children discovered through navigations are inserted, not updated.
            entity.Property(nameof(BaseEntity.Id)).ValueGeneratedNever();
            entity.Property(nameof(BaseEntity.CreatedBy)).HasMaxLength(450);
            entity.Property(nameof(BaseEntity.UpdatedBy)).HasMaxLength(450);
            entity.Property(nameof(BaseEntity.DeletedBy)).HasMaxLength(450);
        }
    }

    private void ConfigureDocument(EntityTypeBuilder<Document> document)
    {
        document.ToTable("documents");
        document.HasQueryFilter(d => d.TenantId == CurrentTenantId && !d.IsDeleted);

        // Optimistic concurrency on PostgreSQL's xmin system column.
        document.Property<uint>("Version").IsRowVersion();

        document.Property(d => d.Status).HasConversion<string>().HasMaxLength(20);
        document.Property(d => d.StoragePath).HasMaxLength(1000);
        document.Property(d => d.PublishedBy).HasMaxLength(450);
        document.Property(d => d.ExtractedText).HasColumnType("text");
        document.Property(d => d.Summary).HasColumnType("text");
        document.Ignore(d => d.CurrentVersion);

        document.OwnsOne(d => d.Metadata, metadata =>
        {
            metadata.Property(m => m.Title).HasColumnName("title").HasMaxLength(500).IsRequired();
            metadata.Property(m => m.Description).HasColumnName("description").HasMaxLength(2000);
            metadata.Property(m => m.Author).HasColumnName("author").HasMaxLength(200);
            metadata.Property(m => m.Subject).HasColumnName("subject").HasMaxLength(500);
            metadata.Property(m => m.Keywords).HasColumnName("keywords").HasMaxLength(1000);
            metadata.Property(m => m.Category).HasColumnName("category").HasMaxLength(100);
            metadata.Property(m => m.Language).HasColumnName("language").HasMaxLength(10);
            metadata.Property(m => m.Classification).HasColumnName("classification").HasConversion<string>().HasMaxLength(20);
            metadata.Property(m => m.ExpiryDate).HasColumnName("expiry_date");
            metadata.Ignore(m => m.CustomProperties);
        });

        document.OwnsOne(d => d.FileInfo, file =>
        {
            file.Property(f => f.FileName).HasColumnName("file_name").HasMaxLength(500).IsRequired();
            file.Property(f => f.ContentType).HasColumnName("content_type").HasMaxLength(200);
            file.Property(f => f.Size).HasColumnName("file_size");
            file.Property(f => f.Extension).HasColumnName("file_extension").HasMaxLength(20);
            file.Property(f => f.Hash).HasColumnName("file_sha256").HasMaxLength(128);
            file.Property(f => f.Type).HasColumnName("file_type").HasConversion<string>().HasMaxLength(20);
        });

        document.HasMany(d => d.Versions).WithOne().HasForeignKey(v => v.DocumentId).OnDelete(DeleteBehavior.Cascade);
        document.HasMany(d => d.Tags).WithOne().HasForeignKey(t => t.DocumentId).OnDelete(DeleteBehavior.Cascade);
        document.HasMany(d => d.Permissions).WithOne().HasForeignKey(p => p.DocumentId).OnDelete(DeleteBehavior.Cascade);
        document.HasMany(d => d.Comments).WithOne().HasForeignKey(c => c.DocumentId).OnDelete(DeleteBehavior.Cascade);
        document.HasOne<Folder>().WithMany().HasForeignKey(d => d.FolderId).OnDelete(DeleteBehavior.SetNull);

        document.HasIndex(d => new { d.TenantId, d.Status });
        document.HasIndex(d => new { d.TenantId, d.FolderId });
        document.HasIndex(d => d.CreatedBy);
    }

    private void ConfigureFolder(EntityTypeBuilder<Folder> folder)
    {
        folder.ToTable("folders");
        folder.HasQueryFilter(f => f.TenantId == CurrentTenantId && !f.IsDeleted);
        folder.Property(f => f.Name).HasMaxLength(200).IsRequired();
        folder.Property(f => f.Description).HasMaxLength(1000);
        folder.HasOne<Folder>().WithMany().HasForeignKey(f => f.ParentFolderId).OnDelete(DeleteBehavior.Restrict);
        folder.HasIndex(f => new { f.TenantId, f.ParentFolderId, f.Name }).IsUnique();
    }
}
