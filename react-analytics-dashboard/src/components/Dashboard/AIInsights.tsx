'use client';

import { useQuery } from '@tanstack/react-query';
import { ArrowPathIcon, SparklesIcon } from '@heroicons/react/24/outline';
import type { InsightsResult } from '@/lib/insights/insights';

async function fetchInsights(): Promise<InsightsResult> {
  const response = await fetch('/api/insights', { cache: 'no-store' });
  if (!response.ok) {
    throw Object.assign(new Error('Failed to load insights'), { status: response.status });
  }
  return response.json() as Promise<InsightsResult>;
}

export function AIInsights() {
  const { data, isLoading, isFetching, error, refetch } = useQuery({
    queryKey: ['insights'],
    queryFn: fetchInsights,
    staleTime: 10 * 60 * 1000,
  });

  return (
    <section
      aria-labelledby="ai-insights-title"
      className="rounded-lg border border-primary-200 bg-gradient-to-br from-primary-50 to-white p-6 dark:border-primary-800 dark:from-primary-900/30 dark:to-gray-800"
    >
      <div className="mb-4 flex items-center justify-between gap-4">
        <div className="flex items-center gap-2">
          <SparklesIcon className="h-5 w-5 text-primary-600 dark:text-primary-400" aria-hidden />
          <h2 id="ai-insights-title" className="text-lg font-semibold text-gray-900 dark:text-white">
            Insights
          </h2>
          {data && (
            <span
              className="rounded-full bg-primary-100 px-2 py-0.5 text-xs font-medium text-primary-700 dark:bg-primary-800 dark:text-primary-200"
              title={data.source === 'llm' ? 'Generated by the configured language model' : 'Generated by built-in rules'}
            >
              {data.source === 'llm' ? 'AI generated' : 'Rule-based'}
            </span>
          )}
        </div>
        <button
          type="button"
          onClick={() => refetch()}
          disabled={isFetching}
          className="inline-flex items-center gap-1 rounded-md px-2 py-1 text-sm text-primary-700 hover:bg-primary-100 disabled:opacity-50 dark:text-primary-300 dark:hover:bg-primary-800/50"
        >
          <ArrowPathIcon className={`h-4 w-4 ${isFetching ? 'animate-spin' : ''}`} aria-hidden />
          Refresh
        </button>
      </div>

      {isLoading ? (
        <ul className="space-y-2" aria-busy="true">
          {Array.from({ length: 3 }).map((_, i) => (
            <li key={i} className="h-4 animate-pulse rounded bg-primary-100 dark:bg-primary-900/50" />
          ))}
        </ul>
      ) : error ? (
        <p className="text-sm text-red-600 dark:text-red-400">Insights are unavailable right now.</p>
      ) : (
        <ul className="list-disc space-y-2 pl-5 text-sm text-gray-700 dark:text-gray-300">
          {data?.highlights.map((highlight) => <li key={highlight}>{highlight}</li>)}
        </ul>
      )}
    </section>
  );
}
