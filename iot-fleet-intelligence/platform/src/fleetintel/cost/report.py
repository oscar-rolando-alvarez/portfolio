"""Markdown rendering for cost estimates, scenario comparisons and sensitivity."""

from __future__ import annotations

from decimal import Decimal

from fleetintel.cost.model import CostReport, FleetProfile, estimate, load_pricing, money

SCENARIOS = (10_000, 1_000_000, 10_000_000)
INTERVALS = (60, 300, 900, 3600)


def _num(x: Decimal) -> str:
    return f"{x:,.0f}"


def render_estimate(r: CostReport, detail: bool = True) -> str:
    p = r.profile
    out = [
        f"**{p.devices:,} devices**, one reading every {p.report_interval_seconds}s, {p.payload_bytes} B payload, "
        f"ingest via `{p.ingest_path}` - pricing table `{r.pricing_version}` ({r.region}).",
        "",
        "| Category | Monthly (USD) | Share |",
        "|---|---:|---:|",
    ]
    for cat, v in sorted(r.by_category.items(), key=lambda kv: -kv[1]):
        share = v / r.total_usd * 100 if r.total_usd else Decimal(0)
        out.append(f"| {cat} | {money(v)} | {share:.1f}% |")
    out += [
        f"| **Total** | **{money(r.total_usd)}** | 100% |",
        "",
        f"Per device per month: **${r.per_device_usd:.4f}** - per million readings: **{money(r.per_million_readings_usd)}** - "
        f"readings/month: {_num(r.volumes['readings'])} - incidents/month: {_num(r.volumes['incidents'])} - "
        f"MSK partitions: {_num(r.volumes['msk_partitions'])}.",
    ]
    if detail:
        out += [
            "",
            "<details><summary>Line items</summary>",
            "",
            "| Category | Item | Quantity | Unit | Monthly (USD) |",
            "|---|---|---:|---|---:|",
        ]
        for it in r.line_items:
            qty = it.quantity / 1_000_000 if it.unit.startswith("million") else it.quantity
            out.append(
                f"| {it.category} | {it.item} | {qty:,.2f} | {it.unit} | {money(it.monthly_usd)} |"
            )
        out += ["", "</details>"]
    if r.recommendations:
        out += ["", "| Optimization | Monthly savings | New total |", "|---|---:|---:|"]
        for rec in r.recommendations:
            out.append(
                f"| {rec.title} | {money(rec.monthly_savings_usd)} | {money(rec.new_total_usd)} |"
            )
    return "\n".join(out)


def render_comparison(base: FleetProfile, devices: tuple[int, ...] = SCENARIOS) -> str:
    reports = [
        estimate(base.model_copy(update={"devices": n}), with_recommendations=False)
        for n in devices
    ]
    cats = sorted(
        {c for r in reports for c in r.by_category},
        key=lambda c: -reports[-1].by_category.get(c, Decimal(0)),
    )
    head = "| Category | " + " | ".join(f"{n:,} devices" for n in devices) + " |"
    out = [head, "|---|" + "---:|" * len(devices)]
    for c in cats:
        out.append(
            f"| {c} | "
            + " | ".join(money(r.by_category.get(c, Decimal(0))) for r in reports)
            + " |"
        )
    out.append(
        "| **Total / month** | " + " | ".join(f"**{money(r.total_usd)}**" for r in reports) + " |"
    )
    out.append(
        "| Per device / month | " + " | ".join(f"${r.per_device_usd:.4f}" for r in reports) + " |"
    )
    return "\n".join(out)


def render_sensitivity(base: FleetProfile, intervals: tuple[int, ...] = INTERVALS) -> str:
    out = [
        "| Report interval | Readings / month | Total / month | Per device | IoT Core share |",
        "|---:|---:|---:|---:|---:|",
    ]
    for s in intervals:
        r = estimate(
            base.model_copy(update={"report_interval_seconds": s}), with_recommendations=False
        )
        iot = r.by_category.get("Ingest (IoT Core)", Decimal(0))
        out.append(
            f"| {s}s | {_num(r.volumes['readings'])} | {money(r.total_usd)} | ${r.per_device_usd:.4f} | "
            f"{iot / r.total_usd * 100:.0f}% |"
        )
    return "\n".join(out)


def render_full_report() -> str:
    pricing = load_pricing()
    base = FleetProfile(devices=1_000_000)
    est = estimate(base)
    return "\n".join(
        [
            "<!-- generated by `fleetintel-cost report` - do not edit by hand -->",
            f"_Pricing assumptions `{pricing['version']}` ({pricing['region']}), list prices without free tier or discounts. "
            "Estimates, not quotes._",
            "",
            "#### Scenario comparison (5-minute reporting, 512 B payload, 0.5 incidents per 1k devices per day)",
            "",
            render_comparison(base),
            "",
            "#### Sensitivity to reporting frequency (1M devices)",
            "",
            render_sensitivity(base),
            "",
            "#### 1M-device baseline and optimization levers",
            "",
            render_estimate(est, detail=False),
            "",
        ]
    )
